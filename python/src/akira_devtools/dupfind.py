#!/usr/bin/env python3
"""dupfind - find duplicate files by content hash. Zero dependencies.

Scans one or more directories, groups files with identical content (by SHA-256),
and reports them. Safe: read-only, never modifies or deletes anything.

Usage:
  dupfind.py path [path2 ...]
  dupfind.py --json path
  dupfind.py --min-size 1024 path       # ignore files smaller than 1 KiB
  dupfind.py --empty path               # also report zero-byte files
  dupfind.py --dedupe-script path > rm.sh  # emit a review-ready rm script

Exit codes: 0 = no duplicates, 1 = duplicates found, 2 = usage/IO error.
"""
import argparse
import hashlib
import json
import os
import sys


def human(n):
    for unit in ("B", "KiB", "MiB", "GiB", "TiB"):
        if n < 1024 or unit == "TiB":
            return f"{n:.0f}{unit}" if unit == "B" else f"{n:.1f}{unit}"
        n /= 1024


def iter_files(paths):
    for root_path in paths:
        if os.path.isfile(root_path):
            yield root_path
            continue
        for dirpath, dirnames, filenames in os.walk(root_path, followlinks=False):
            dirnames.sort()
            for name in sorted(filenames):
                full = os.path.join(dirpath, name)
                if os.path.isfile(full):
                    yield full


def sha256_of(path, chunk=1 << 20):
    h = hashlib.sha256()
    try:
        with open(path, "rb") as f:
            while True:
                block = f.read(chunk)
                if not block:
                    break
                h.update(block)
    except (OSError, PermissionError):
        return None
    return h.hexdigest()


def collect(paths, min_size, include_empty):
    # First group by size to skip hashing files with unique sizes.
    by_size = {}
    for f in iter_files(paths):
        try:
            st = os.stat(f)
        except OSError:
            continue
        if st.st_size == 0:
            if not include_empty:
                continue
        elif st.st_size < min_size:
            continue
        by_size.setdefault(st.st_size, []).append(f)

    groups = {}
    for size, files in by_size.items():
        if len(files) < 2:
            continue
        for f in files:
            digest = sha256_of(f)
            if digest is None:
                continue
            groups.setdefault((digest, size), []).append(f)
    dups = {k: sorted(v) for k, v in groups.items() if len(v) > 1}
    return dups


def main(argv=None):
    ap = argparse.ArgumentParser(description="Find duplicate files by content hash.")
    ap.add_argument("paths", nargs="+", help="files or directories to scan")
    ap.add_argument("--json", action="store_true", help="machine-readable output")
    ap.add_argument("--min-size", type=int, default=1, help="ignore files smaller than N bytes (default 1)")
    ap.add_argument("--empty", action="store_true", help="include zero-byte files")
    ap.add_argument("--dedupe-script", action="store_true",
                    help="print a shell script that would remove all but one copy per group")
    args = ap.parse_args(argv)

    missing = [p for p in args.paths if not os.path.exists(p)]
    if missing:
        for m in missing:
            sys.stderr.write(f"dupfind: no such path: {m}\n")
        return 2

    dups = collect(args.paths, args.min_size, args.empty)

    total_wasted = 0
    for (digest, size), files in dups.items():
        total_wasted += size * (len(files) - 1)

    if args.dedupe_script:
        print("#!/bin/sh")
        print("# Generated by dupfind. REVIEW before running. Keeps the first path in each group.")
        for (digest, size), files in sorted(dups.items(), key=lambda kv: -kv[0][1]):
            keep = files[0]
            for f in files[1:]:
                print(f"# dup of {keep!r} ({human(size)})")
                print("rm -- " + shell_quote(f))
        return 1 if dups else 0

    if args.json:
        out = {
            "groups": [
                {"sha256": d, "size": s, "wasted": s * (len(fs) - 1), "files": fs}
                for (d, s), fs in sorted(dups.items(), key=lambda kv: -kv[0][1])
            ],
            "total_wasted": total_wasted,
            "duplicate_groups": len(dups),
        }
        print(json.dumps(out, indent=2))
        return 1 if dups else 0

    if not dups:
        print("No duplicates found.")
        return 0

    for (digest, size), files in sorted(dups.items(), key=lambda kv: -kv[0][1]):
        print(f"{digest[:16]}  {human(size):>9}  x{len(files)}")
        for f in files:
            print(f"    {f}")
        print()
    print(f"{len(dups)} duplicate group(s), {human(total_wasted)} reclaimable.")
    return 1


def shell_quote(s):
    return "'" + s.replace("'", "'\\''") + "'"


if __name__ == "__main__":
    sys.exit(main())
